"""Write the member's own Claude Code skill (~/.claude/skills/ghl-cli/SKILL.md).

The template carries four placeholders: {{GHL}} (absolute path of this install's
`ghl` script), {{SETUP}} (absolute path of its SETUP.md), {{ROOT}} (the install
folder holding SETUP.md and VERSION, used by the guarded removal command) and
{{BUILDERS}} (its builders/ folder). The file we write
starts with GENERATED_MARK; a file without the mark is somebody's hand-written
skill and is never overwritten unless the caller passes force=True.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

GENERATED_MARK = "<!-- generated by: ghl skill install -->"

_PKG = Path(__file__).resolve().parents[1]
TEMPLATE = _PKG / "skills" / "SKILL.template.md"


class SkillExists(Exception):
    """A skill file is already there and was not generated by us."""


def skills_dir() -> Path:
    env = os.environ.get("CLAUDE_SKILLS_DIR")
    return Path(env) if env else Path.home() / ".claude" / "skills"


def setup_md_path() -> Path:
    """SETUP.md at the install root, the same root the VERSION file lives in."""
    return _PKG.parents[1] / "SETUP.md"


def find_ghl() -> Path | None:
    """The `ghl` console script next to the running python, or None."""
    name = "ghl.exe" if sys.platform == "win32" else "ghl"
    candidate = Path(os.path.abspath(sys.executable)).parent / name
    return candidate if candidate.is_file() else None


def is_generated(text: str) -> bool:
    """True only when the mark is the first line after the frontmatter, where install puts it."""
    text = text.replace("\r\n", "\n")
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end == -1:
            return False
        text = text[end + len("\n---\n"):]
    return text.split("\n", 1)[0].strip() == GENERATED_MARK


def render(ghl_path: Path, setup_md: Path) -> str:
    text = TEMPLATE.read_text(encoding="utf-8")
    # Filled here with this platform's own path rules, so the skill never has to work out
    # the folder from a path string (dirname of a backslash path is "." in bash).
    root = Path(os.path.abspath(setup_md)).parent
    builders = root / "builders"
    text = (text.replace("{{GHL}}", str(ghl_path)).replace("{{SETUP}}", str(setup_md))
            .replace("{{ROOT}}", str(root)).replace("{{BUILDERS}}", str(builders)))
    # the YAML frontmatter must stay first; the mark goes right after it
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4) + len("\n---\n")
        return f"{text[:end]}{GENERATED_MARK}\n{text[end:]}"
    return f"{GENERATED_MARK}\n{text}"


def install_skill(ghl_path: Path, setup_md: Path, force: bool = False) -> Path:
    target = skills_dir() / "ghl-cli" / "SKILL.md"
    if target.exists():
        existing = target.read_text(encoding="utf-8", errors="replace")
        if not is_generated(existing):
            if not force:
                raise SkillExists(str(target))
            backup = target.with_name("SKILL.md.bak")
            backup.write_text(existing, encoding="utf-8")
            install_skill.last_backup = backup
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(render(Path(ghl_path), Path(setup_md)), encoding="utf-8")
            return target
    install_skill.last_backup = None
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(Path(ghl_path), Path(setup_md)), encoding="utf-8")
    return target
